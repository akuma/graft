"""Codex integration: generate profile files and launch codex.

The user's ~/.codex/config.toml is never modified. Each provider gets its own
layered profile (`$CODEX_HOME/<prefix><provider>.config.toml`), which codex
loads on top of the base config via `codex --profile <name>`. That keeps the
normal codex setup intact while inheriting its skills, AGENTS.md, hooks, MCP
servers and session storage.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

from . import catalog, creds, proxy
from .config import Config, Provider


def profile_path(config: Config, provider: Provider) -> Path:
    return config.codex_home / f"{provider.profile_name(config.profile_prefix)}.config.toml"


def profile_body(config: Config, provider: Provider) -> str:
    provider_id = provider.profile_name(config.profile_prefix)
    default_model = provider.models[0] if provider.models else ""
    base_url = (
        f"http://127.0.0.1:{provider.port}/v1" if provider.is_thin else provider.upstream
    )
    lines = [
        "# generated by graft; edit ~/.config/graft/config.toml instead of this file",
        f'# provider: {provider.name} ({provider.transport})',
        "",
        f'model = "{default_model}"',
        f'model_provider = "{provider_id}"',
    ]
    if provider.context_window:
        lines.append(f"model_context_window = {provider.context_window}")
    catalog_path = catalog.catalog_path(config, provider)
    if provider.models:
        # keeps /model limited to this provider's models instead of the bundled GPT list
        lines.append(f'model_catalog_json = "{catalog_path}"')
    lines.append("suppress_unstable_features_warning = true")
    if provider.disable_web_search:
        # top level key, must appear before the first table
        lines.append('web_search = "disabled"')
    if provider.disable_agent_tools:
        lines += ["", "[agents]", "enabled = false"]
    lines += [
        "",
        f"[model_providers.{provider_id}]",
        f'name = "{provider.label}"',
        f'base_url = "{base_url}"',
        f'env_key = "{provider.env_var()}"',
        'wire_api = "responses"',
        "",
    ]
    return "\n".join(lines)


def sync(config: Config, verbose: bool = True) -> list[Path]:
    written = []
    for provider in config.providers.values():
        catalog.write(config, provider, verbose=verbose)
    for provider in config.providers.values():
        path = profile_path(config, provider)
        path.parent.mkdir(parents=True, exist_ok=True)
        body = profile_body(config, provider)
        if path.exists() and path.read_text(encoding="utf-8") == body:
            continue
        path.write_text(body, encoding="utf-8")
        written.append(path)
        if verbose:
            print(f"wrote {path}")
    return written


def env_for(provider: Provider) -> dict[str, str]:
    """Value codex sends as its bearer token.

    Thin transports own the credential, so codex only needs a non-empty
    placeholder. Direct transports need the real key.
    """
    if provider.is_thin:
        return {provider.env_var(): "graft-managed"}
    if provider.auth == "api-key":
        return {provider.env_var(): creds.api_key(provider)}
    if provider.auth == "borrow" and provider.auth_source == "grok-cli":
        return {provider.env_var(): creds.grok_session()["key"]}
    raise SystemExit(f"provider '{provider.name}': unsupported auth {provider.auth}/{provider.auth_source}")


def launch(config: Config, provider: Provider, model: str | None, codex_args: list[str]) -> None:
    codex = shutil.which("codex")
    if not codex:
        raise SystemExit("codex not found on PATH")

    if provider.is_thin:
        proxy.ensure(config, provider)
        for note in creds.check(provider):
            print(f"graft: {note}", file=sys.stderr)

    env = dict(os.environ)
    env["CODEX_HOME"] = str(config.codex_home)
    env.update(env_for(provider))

    argv = [codex, "--profile", provider.profile_name(config.profile_prefix)]
    if model:
        argv += ["-m", model]
    argv += codex_args
    os.execvpe(codex, argv, env)


def run_capture(argv: list[str], env: dict[str, str]) -> int:
    return subprocess.call(argv, env=env)
