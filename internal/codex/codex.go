// Package codex writes Codex profiles and launches the codex binary.
//
// The user's config.toml is never modified. Each provider gets a layered
// profile, loaded with `codex --profile`, so skills, hooks, MCP and sessions
// stay shared with a normal Codex install.
package codex

import (
	"fmt"
	"os"
	"os/exec"
	"strings"
	"syscall"

	"github.com/akuma/graft/internal/catalog"
	"github.com/akuma/graft/internal/config"
	"github.com/akuma/graft/internal/creds"
	"github.com/akuma/graft/internal/proxy"
)

// ProfilePath is $CODEX_HOME/<prefix><provider>.config.toml.
func ProfilePath(cfg *config.Config, p *config.Provider) string {
	return cfg.CodexHome + "/" + p.ProfileName(cfg.ProfilePrefix) + ".config.toml"
}

// ProfileBody is the layered Codex config for one provider.
func ProfileBody(cfg *config.Config, p *config.Provider) string {
	id := p.ProfileName(cfg.ProfilePrefix)
	model := ""
	if len(p.Models) > 0 {
		model = p.Models[0]
	}
	baseURL := p.Upstream
	if p.IsThin() {
		baseURL = fmt.Sprintf("http://127.0.0.1:%d/v1", p.Port)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by graft; edit %s instead of this file\n", cfg.Path)
	fmt.Fprintf(&b, "# provider: %s (%s)\n\n", p.Name, p.Transport)
	fmt.Fprintf(&b, "model = %q\n", model)
	fmt.Fprintf(&b, "model_provider = %q\n", id)
	if p.ContextWindow > 0 {
		fmt.Fprintf(&b, "model_context_window = %d\n", p.ContextWindow)
	}
	if len(p.Models) > 0 {
		fmt.Fprintf(&b, "model_catalog_json = %q\n", catalog.Path(cfg, p))
	}
	b.WriteString("suppress_unstable_features_warning = true\n")
	if p.DisableWebSearch {
		b.WriteString("web_search = \"disabled\"\n")
	}
	if p.DisableAgentTools {
		b.WriteString("\n[agents]\nenabled = false\n")
	}
	fmt.Fprintf(&b, "\n[model_providers.%s]\n", id)
	fmt.Fprintf(&b, "name = %q\n", p.Label)
	fmt.Fprintf(&b, "base_url = %q\n", baseURL)
	fmt.Fprintf(&b, "env_key = %q\n", p.EnvVar())
	b.WriteString("wire_api = \"responses\"\n")
	return b.String()
}

// Sync rewrites catalogs and profiles that changed.
func Sync(cfg *config.Config, verbose bool) error {
	for _, name := range cfg.Order {
		if _, err := catalog.Write(cfg, cfg.Providers[name], verbose); err != nil {
			return err
		}
	}
	for _, name := range cfg.Order {
		p := cfg.Providers[name]
		path := ProfilePath(cfg, p)
		body := ProfileBody(cfg, p)
		existing, err := os.ReadFile(path)
		if err == nil && string(existing) == body {
			continue
		}
		if err := os.MkdirAll(cfg.CodexHome, 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			return err
		}
		if verbose {
			fmt.Println("wrote " + path)
		}
	}
	return nil
}

func envFor(p *config.Provider) (string, error) {
	if p.IsThin() {
		return "graft-managed", nil
	}
	switch p.Auth {
	case "api-key":
		return creds.APIKey(p)
	case "borrow":
		if p.AuthSource != "grok-cli" {
			return "", fmt.Errorf("provider %q: unsupported auth %s/%s", p.Name, p.Auth, p.AuthSource)
		}
		session, err := creds.GrokSession()
		if err != nil {
			return "", err
		}
		return session.Key, nil
	default:
		return "", fmt.Errorf("provider %q: unsupported auth %s", p.Name, p.Auth)
	}
}

// Launch replaces this process with codex. It does not return on success.
func Launch(cfg *config.Config, p *config.Provider, model string, args []string) error {
	bin, err := exec.LookPath("codex")
	if err != nil {
		return fmt.Errorf("codex not found on PATH")
	}
	if p.IsThin() {
		if err := proxy.Ensure(cfg, p); err != nil {
			return err
		}
		for _, note := range creds.Check(p) {
			fmt.Fprintf(os.Stderr, "graft: %s\n", note)
		}
	}
	token, err := envFor(p)
	if err != nil {
		return err
	}
	argv := []string{bin, "--profile", p.ProfileName(cfg.ProfilePrefix)}
	if model != "" {
		argv = append(argv, "-m", model)
	}
	argv = append(argv, args...)
	env := os.Environ()
	env = append(env, "CODEX_HOME="+cfg.CodexHome, p.EnvVar()+"="+token)
	return syscall.Exec(bin, argv, env)
}
